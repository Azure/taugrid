def _find_handle(module, kind):
    """Return the @tau.{kind} handle in module; exit with a clear error otherwise.

    `kind` is "train" or "eval". The wrapper picks which to look for based
    on the rendered manifest's eval.cpu_workers field (rayjob-eval pods
    have it set; rayjob/job pods don't). Same module can carry both
    handles — e.g. for the experiment.py pattern that the tau-py
    orchestrator submits as two separate RayJobs.
    """
    sentinel = "_tau_" + kind + "_handle"
    # Dedupe by object identity so `alias = train` (a re-export) doesn't
    # falsely trip the "multiple handles" guard.
    seen_ids = set()
    candidates = []
    for name in dir(module):
        obj = getattr(module, name)
        if not getattr(obj, sentinel, False):
            continue
        if id(obj) in seen_ids:
            continue
        seen_ids.add(id(obj))
        candidates.append((name, obj))
    if not candidates:
        sys.exit(
            "tau-py wrapper: no @tau." + kind +
            "-decorated function found in " + USER_MODULE_PATH
        )
    if len(candidates) > 1:
        names = ", ".join(n for n, _ in candidates)
        sys.exit(
            "tau-py wrapper: multiple @tau." + kind +
            "-decorated functions found (" + names + "); only one per "
            "module is supported in V1."
        )
    return candidates[0][1]


def _profile_runtime_rank():
    for key in ("TAU_RANK", "RANK", "WORLD_RANK", "OMPI_COMM_WORLD_RANK", "PMI_RANK"):
        value = os.environ.get(key, "")
        if value:
            return value
    try:
        from ray import train as _ray_train
        rank = _ray_train.get_context().get_world_rank()
        if rank is not None:
            return str(rank)
    except Exception:
        pass
    local_rank = os.environ.get("LOCAL_RANK", "")
    if local_rank:
        return local_rank
    return "0"


def _profile_rank_selected(runtime_rank):
    rank_filter = (os.environ.get("TAU_PROFILE_RANK", "0") or "0").strip().lower()
    if rank_filter == "all":
        return True, rank_filter
    ranks = [part.strip() for part in rank_filter.split(",") if part.strip()]
    return runtime_rank in ranks, rank_filter


def _safe_profile_rank(rank):
    safe = []
    for ch in str(rank):
        if ch.isalnum() or ch in ("_", ".", "-"):
            safe.append(ch)
        else:
            safe.append("-")
    return "".join(safe) or "unknown"


