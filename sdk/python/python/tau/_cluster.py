def _install_tau_shim(manifest=None):
    """Inject a minimal tau module into sys.modules.

    The researcher's source imports `import tau` (or `from tau import
    train, eval, Ctx`) and writes `@tau.train(...)` or `@tau.eval(...)`.
    On the cluster tau-py isn't installed, so we forge a stub module that
    produces the same handle shape (object with ``_tau_train_handle = True``
    or ``_tau_eval_handle = True`` plus a ``_fn`` attribute) the local SDK
    does.

    Calling the handle on-cluster raises (the wrapper invokes ``_fn(ctx)``
    directly with a populated Ctx; you should never call it yourself), and
    ``.submit()`` raises (would recurse).
    """

    class _ClusterCtxStub:
        # Only used for `tau.workloads.Ctx` type hints in user code; the
        # real ctx the wrapper passes in is built by _build_cluster_ctx.
        pass

    class _ClusterTrainHandle:
        # Real class with class-level dunders so `handle()` triggers
        # __call__ (instance attrs on SimpleNamespace would be ignored by
        # Python's special-method lookup).
        _tau_train_handle = True

        def __init__(self, fn, kwargs):
            self._fn = fn
            self._kwargs = kwargs
            self.__name__ = getattr(fn, "__name__", "train")

        def __call__(self, *a, **kw):
            raise RuntimeError(
                "tau-py: refusing to call the training function "
                "directly inside a cluster-submitted job. The wrapper "
                "invokes it for you with a populated Ctx."
            )

        def submit(self, *a, **kw):
            raise RuntimeError(
                "tau-py: refusing to .submit() from inside a "
                "cluster-submitted job (would recurse). Submit from "
                "your local machine, or from a CI runner."
            )

    class _ClusterEvalHandle:
        # Same shape as _ClusterTrainHandle but with the eval sentinel
        # so _find_handle can route to the right code path.
        _tau_eval_handle = True

        def __init__(self, fn, kwargs):
            self._fn = fn
            self._kwargs = kwargs
            self.__name__ = getattr(fn, "__name__", "eval")

        def __call__(self, *a, **kw):
            raise RuntimeError(
                "tau-py: refusing to call the eval function directly "
                "inside a cluster-submitted job. The wrapper invokes "
                "it for you with a populated Ctx."
            )

        def submit(self, *a, **kw):
            raise RuntimeError(
                "tau-py: refusing to .submit() from inside a "
                "cluster-submitted job (would recurse)."
            )

    def _train(*args, **kwargs):
        if args:
            raise TypeError("tau.train: pass parameters as keyword arguments")

        def decorator(fn):
            return _ClusterTrainHandle(fn, dict(kwargs))

        return decorator

    def _eval(*args, **kwargs):
        if args:
            raise TypeError("tau.eval: pass parameters as keyword arguments")

        def decorator(fn):
            return _ClusterEvalHandle(fn, dict(kwargs))

        return decorator

    config = types.ModuleType("tau.config")
    exec(_render_config_shim(manifest), config.__dict__)

    datasets = types.ModuleType("tau.datasets")
    exec(_TAU_SHIM_DATASETS, datasets.__dict__)
    entrypoints = types.ModuleType("tau.entrypoints")
    exec(_TAU_SHIM_ENTRYPOINTS, entrypoints.__dict__)
    jsonl = types.ModuleType("tau.jsonl")
    exec(_TAU_SHIM_JSONL, jsonl.__dict__)

    workloads = types.ModuleType("tau.workloads")
    workloads.train = _train
    workloads.eval = _eval
    workloads.Ctx = _ClusterCtxStub
    tau = types.ModuleType("tau")
    tau.__path__ = []
    tau.datasets = datasets
    tau.entrypoints = entrypoints
    tau.jsonl = jsonl
    tau.workloads = workloads
    # Mirror the local package's top-level exports so
    # `from tau import train, eval, Ctx` works on-cluster too.
    tau.train = _train
    tau.eval = _eval
    tau.Ctx = _ClusterCtxStub
    tau.SecretRef = config.SecretRef
    tau.call_staged_function = entrypoints.call_staged_function
    tau.config = config.config
    tau.dataset_file_reference = datasets.dataset_file_reference
    tau.load_config = config.load_config
    tau.load_staged_function = entrypoints.load_staged_function
    tau.load_staged_module = entrypoints.load_staged_module
    tau.pvc_mount = config.pvc_mount
    tau.read_jsonl_objects = jsonl.read_jsonl_objects
    tau.secret = config.secret
    tau.secret_ref = config.secret_ref
    tau.__all__ = [
        "Ctx",
        "SecretRef",
        "call_staged_function",
        "config",
        "dataset_file_reference",
        "datasets",
        "entrypoints",
        "eval",
        "jsonl",
        "load_config",
        "load_staged_function",
        "load_staged_module",
        "pvc_mount",
        "read_jsonl_objects",
        "secret",
        "secret_ref",
        "train",
        "workloads",
    ]
    sys.modules["tau"] = tau
    sys.modules["tau.datasets"] = datasets
    sys.modules["tau.entrypoints"] = entrypoints
    sys.modules["tau.jsonl"] = jsonl
    sys.modules["tau.workloads"] = workloads
    sys.modules["tau.config"] = config


def _user_module_name(path):
    name = pathlib.Path(path).stem
    if not name.isidentifier():
        sys.exit(
            "tau-py wrapper: staged user module filename must be an "
            "importable Python module name, got " + pathlib.Path(path).name
        )
    if name == "tau":
        sys.exit(
            "tau-py wrapper: staged user module filename " +
            pathlib.Path(path).name +
            " is reserved because it would shadow the cluster tau shim"
        )
    return name


def _ensure_user_module_dir_on_sys_path(path):
    module_dir = str(pathlib.Path(path).resolve().parent)
    if module_dir not in sys.path:
        sys.path.insert(0, module_dir)


def _load_user_module(path):
    module_name = _user_module_name(path)
    _ensure_user_module_dir_on_sys_path(path)
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        sys.exit("tau-py wrapper: cannot load user module at " + path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def _write_importable_tau_shim(root, manifest=None):
    tau_dir = pathlib.Path(root) / "tau"
    tau_dir.mkdir(parents=True, exist_ok=True)
    (tau_dir / "__init__.py").write_text(_TAU_SHIM_INIT)
    (tau_dir / "config.py").write_text(_render_config_shim(manifest))
    (tau_dir / "datasets.py").write_text(_TAU_SHIM_DATASETS)
    (tau_dir / "entrypoints.py").write_text(_TAU_SHIM_ENTRYPOINTS)
    (tau_dir / "workloads.py").write_text(_TAU_SHIM_WORKLOADS)
    (tau_dir / "jsonl.py").write_text(_TAU_SHIM_JSONL)


