def render_wrapper(user_module_filename: str) -> str:
    """Substitute the user-module filename into the wrapper template."""
    replacements = {
        "__USER_MODULE_FILENAME__": repr(user_module_filename),
        "__TAU_SHIM_DATASETS_SOURCE__": repr(_cluster_helper_source("datasets.py")),
        "__TAU_SHIM_ENTRYPOINTS_SOURCE__": repr(_cluster_helper_source("entrypoints.py")),
        "__TAU_SHIM_JSONL_SOURCE__": repr(_cluster_helper_source("jsonl.py")),
    }
    rendered = CLUSTER_WRAPPER_TEMPLATE
    for marker, value in replacements.items():
        rendered = rendered.replace(marker, value)
    return rendered


def _cluster_helper_source(filename: str) -> str:
    """Read the real helper source that the cluster shim embeds."""
    return resources.files("tau").joinpath(filename).read_text(encoding="utf-8")
