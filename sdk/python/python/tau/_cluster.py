def _finalize_train_artifacts(ctx):
    if not _is_primary_process():
        return
    artifact = _checkpoint_artifact_from_manifest(ctx.manifest)
    if artifact is None:
        return
    src = next((candidate for candidate in _artifact_sources(ctx, artifact) if candidate.exists()), None)
    if src is None:
        tried = ", ".join(p.as_posix() for p in _artifact_sources(ctx, artifact))
        raise RuntimeError(
            "tau-py wrapper: declared checkpoint artifact " + repr(artifact) +
            " was not found after training succeeded. Tried: " + tried
        )
    dst = _artifact_destination(ctx, artifact)
    started = datetime.datetime.now(datetime.timezone.utc)
    start = time.monotonic()
    _copy_artifact(src, dst)
    duration_ms = int((time.monotonic() - start) * 1000)
    completed = datetime.datetime.now(datetime.timezone.utc)
    stats = _artifact_stats(dst)
    record = {
        "name": "checkpoint",
        "manifest_path": artifact,
        "source_path": src.as_posix(),
        "durable_path": dst.as_posix(),
        "status": "ready",
        "upload_started_at": started.isoformat(),
        "upload_completed_at": completed.isoformat(),
        "upload_duration_ms": duration_ms,
    }
    record.update(stats)
    index = {
        "schema_version": 1,
        "run": ctx.name,
        "namespace": os.environ.get("POD_NAMESPACE", ""),
        "resource_name": os.environ.get("TAU_RESOURCE_NAME", ""),
        "created_at": completed.isoformat(),
        "hot_root": ctx.checkpoints_dir.as_posix(),
        "durable_root": ctx.durable_checkpoints_dir.as_posix(),
        "storage_probe": {
            "status": ctx.storage_hot_status,
            "reason": ctx.storage_hot_reason,
            "write_mbps": ctx.storage_hot_write_mbps,
        },
        "artifacts": [record],
    }
    artifact_index_path = ctx.durable_checkpoints_dir / "finetunes" / ctx.name / "artifacts.json"
    _write_json_atomic(artifact_index_path, index)
    model_record = _model_registry_record(ctx, index, artifact_index_path, completed)
    _write_model_registry_records(ctx, model_record)
    print(
        "tau-py wrapper: finalized checkpoint artifact " + repr(artifact) +
        " to " + dst.as_posix() +
        " (duration_ms=" + str(duration_ms) + ")",
        flush=True,
    )


