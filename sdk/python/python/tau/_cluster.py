def _cuda_profiler_api_call(name):
    import torch

    cudart = torch.cuda.cudart()
    fn = getattr(cudart, name)
    status = fn()
    if status not in (None, 0):
        raise RuntimeError("tau profiler: " + name + " returned " + str(status))


def _start_cuda_profile_window(warmup_seconds, active_seconds):
    stop_event = threading.Event()
    errors = []
    state = {"started": False, "stopped": False, "lock": threading.Lock()}

    def _stop_once():
        with state["lock"]:
            if not state.get("started") or state.get("stopped"):
                return
            _cuda_profiler_api_call("cudaProfilerStop")
            state["stopped"] = True

    def _timer():
        try:
            if warmup_seconds > 0 and stop_event.wait(warmup_seconds):
                return
            if stop_event.is_set():
                return
            with state["lock"]:
                _cuda_profiler_api_call("cudaProfilerStart")
                state["started"] = True
            if not stop_event.wait(active_seconds):
                _stop_once()
        except BaseException as exc:
            errors.append(repr(exc))

    thread = threading.Thread(target=_timer, name="tau-nsys-cuda-profiler-window", daemon=True)
    thread.start()
    return stop_event, thread, state, errors


def _finish_cuda_profile_window(stop_event, thread, state, errors):
    stop_event.set()
    with state["lock"]:
        should_stop = state.get("started") and not state.get("stopped")
    if should_stop:
        with state["lock"]:
            if state.get("started") and not state.get("stopped"):
                _cuda_profiler_api_call("cudaProfilerStop")
                state["stopped"] = True
    thread.join(timeout=5)
    if errors:
        raise RuntimeError("tau profiler: CUDA profiler API failed: " + "; ".join(errors))


def _run_profiled_worker(call_target):
    mode = (os.environ.get("TAU_PROFILE_MODE", "") or "").strip().lower()
    if not mode:
        return call_target()
    if mode != "nsys":
        raise RuntimeError("tau profiler: unsupported TAU_PROFILE_MODE=" + repr(mode) + " (expected 'nsys')")

