def _load_json_if_exists(path):
    if not path.is_file():
        return None, ""
    with path.open() as f:
        return json.load(f), path.as_posix()


def _numeric_metrics(value, prefix=""):
    out = {}
    if isinstance(value, dict):
        for key, child in value.items():
            if not isinstance(key, str):
                continue
            child_prefix = key if not prefix else prefix + "." + key
            out.update(_numeric_metrics(child, child_prefix))
        return out
    if isinstance(value, bool):
        return out
    if isinstance(value, (int, float)):
        out[prefix] = float(value)
    return out


def _load_metrics_summary(ctx):
    for path in _metric_candidates(ctx):
        raw, raw_path = _load_json_if_exists(path)
        if raw is None:
            continue
        return {
            "path": raw_path,
            "numeric": _numeric_metrics(raw),
            "raw": raw,
        }
    return {"path": "", "numeric": {}, "raw": {}}


def _primary_metric(model_metadata, numeric_metrics):
    name = model_metadata.get("primary_metric") or ""
    if not name:
        for candidate in ("loss", "eval.loss", "train.loss", "score", "accuracy"):
            if candidate in numeric_metrics:
                name = candidate
                break
    if not name:
        return {}
    metric = {"name": name}
    if name in numeric_metrics:
        metric["value"] = numeric_metrics[name]
    direction = model_metadata.get("metric_direction") or ("lower" if "loss" in name else "higher")
    metric["direction"] = direction
    return metric


