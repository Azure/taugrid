def _build_cluster_ctx(manifest_path, smoke_pairs):
    """Build a Ctx mirroring what the embedded Sample trainer would see."""
    import yaml  # part of the entrypoint pip install
    with open(manifest_path) as f:
        manifest = yaml.safe_load(f) or {}

    def _envp(key, default=""):
        v = os.environ.get(key, default)
        return pathlib.Path(v) if v else None

    class Ctx:
        pass

    ctx = Ctx()
    ctx.name = manifest.get("name", "")
    compute = manifest.get("compute") or {}
    ctx.gpus = int(compute.get("gpus", 0))
    # Default workers to 1 so an older manifest (no compute.workers)
    # behaves byte-identically to the v1.0 single-node path.
    ctx.workers = int(compute.get("workers", 1) or 1)
    ctx.smoke_pairs = int(smoke_pairs)
    ctx.manifest = manifest
    ctx.manifest_path = pathlib.Path(manifest_path)
    ctx.data_dir = _envp("TAU_DATA_DIR", "/data")
    ctx.hot_dir = _envp("TAU_HOT_DIR", "/mnt")
    ctx.datasets_dir = _envp("TAU_DATASETS_DIR", "/mnt/datasets")
    ctx.checkpoints_dir = _envp("TAU_CHECKPOINTS_DIR", "/mnt/checkpoints")
    ctx.durable_datasets_dir = _envp("TAU_DURABLE_DATASETS_DIR", "/data/datasets")
    ctx.durable_checkpoints_dir = _envp("TAU_DURABLE_CHECKPOINTS_DIR", "/data/checkpoints")
    ctx.storage_hot_status = os.environ.get("TAU_STORAGE_HOT_STATUS", "hot")
    ctx.storage_hot_reason = os.environ.get("TAU_STORAGE_HOT_REASON", "")
    raw_hot_mbps = os.environ.get("TAU_STORAGE_HOT_WRITE_MBPS", "")
