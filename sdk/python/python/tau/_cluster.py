"""Cluster-side runtime: the wrapper that runs on the Ray head pod.

This module is read as a string (`CLUSTER_WRAPPER_TEMPLATE`) by `tau.workloads`
and shipped to the cluster as `train.py` via `tau run --config`. It must be self-contained — the cluster image only
guarantees Python 3.10 + torch + the deps the entrypoint pip-installs. There
is **no** tau-py install on the cluster.

To make `import tau` work in the researcher's module on the cluster (since
tau-py isn't installed there), the wrapper installs a minimal in-memory
shim into `sys.modules["tau"]` *before* importlib loads the user module.
For eval Ray workers, it also writes the same shim as an importable package
inside the Ray runtime_env working_dir because sys.modules is process-local.
The shim's `train()` decorator returns the same `_TrainHandle`-shaped
object the local SDK does — but on the cluster its `.submit()` raises
(you can't submit from inside a job; you'd recurse).
"""

